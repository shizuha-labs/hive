"""HIVE-1242 / HIVE-1263: agent portrait avatar URLs.

Every identity in the system must have a valid avatar (operator 2026-08):
- Named agents with a hand-published portrait keep their identity portrait.
- EVERY other agent resolves to a deterministic avatar from the hosted
  "stock" pool — so no agent ever renders as bare initials or 404s.

Two resolution tiers, in order:
1. Curated named portrait — ``/avatars/<username>.png`` (Home-published).
2. Stock pool — ``/avatars/stock/<seed % N>.png`` where the seed is a stable
   hash of the lowercase username, so each agent's avatar is stable per
   identity and effectively random across agents, with zero storage.

The frontend then requests an image only when URL != None and renders the
deterministic initials fallback otherwise (no 404 burst, HIVE-1242). ``None``
is returned ONLY for empty/unknown-structure input (never a valid username).

The stock pool lives in ``shizuha-labs/home`` @ ``frontend/public/avatars/stock/*.png``
generated by ``home/scripts/generate_avatars.py``. Keep ``AVATAR_STOCK_SIZE`` in
lockstep with the generated pool size.
"""
import hashlib

from django.conf import settings

# Named agents with a published portrait — shizuha-labs/home frontend/public/avatars/.
# Keep sorted and lowercase; matching is case-insensitive.
AVATAR_USERNAMES = frozenset({
    'akira', 'aoi', 'banto', 'claw', 'cora', 'fumi', 'hana', 'haru', 'haruka',
    'hermes', 'hiro', 'ichi', 'jun', 'kai', 'kei', 'lex', 'lina', 'mika', 'mio',
    'misaki', 'nagi', 'nao', 'ni', 'pia', 'recon', 'rei', 'reika', 'ren', 'revi',
    'rin', 'ryo', 'saki', 'san', 'sana', 'sara', 'scout', 'shion', 'shizuha',
    'sora', 'tomo', 'yuki', 'zen',
})

# Size of the generated stock pool (home/frontend/public/avatars/stock/000..N-1).
# Must match the number of PNGs emitted by home/scripts/generate_avatars.py.
AVATAR_STOCK_SIZE = 160

# The deterministic seed for a username/seed string. Shared algorithm with the
# id service so a user's default avatar is identical on Hive and on ID/home.
def avatar_seed(key):
    digest = hashlib.sha256(str(key or '').strip().lower().encode('utf-8')).digest()
    return int.from_bytes(digest[:4], 'big')


# Full base URL to the published avatars. Overridable per environment; the
# portraits are served from the home origin, decoupled from where Hive is hosted.
DEFAULT_AVATAR_BASE_URL = 'https://shizuha.com/avatars'


def _base_url():
    return str(getattr(settings, 'AGENT_AVATAR_BASE_URL', DEFAULT_AVATAR_BASE_URL) or '').rstrip('/')


def avatar_url_for(username):
    """Return the full portrait URL for ``username`` — always for a valid
    username (curated portrait or deterministic stock pick); ``None`` only for
    empty input (never a valid identity).

    ``None`` is the signal for the frontend to render initials WITHOUT issuing a
    request known to 404. Case-insensitive; safe for empty/None input.
    """
    if not username:
        return None
    key = str(username).strip().lower()
    base = _base_url()
    if not base:
        # Fail-soft by construction: with no base URL configured, never emit a
        # URL that would resolve against the wrong origin.
        return None
    if key in AVATAR_USERNAMES:
        return f'{base}/{key}.png'
    # Stable stock avatar for every other identity (HIVE-1263): deterministic
    # per username → stable across surfaces, random-looking across identities.
    idx = avatar_seed(key) % AVATAR_STOCK_SIZE
    return f'{base}/stock/{idx:03d}.png'
